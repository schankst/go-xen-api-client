package main

import (
	"slices"
	"strings"
	"testing"
)

func TestChunksFromSource(t *testing.T) {
	src := `(* comment *)
let a = add_error "A"

let b =
  add_error "B"
(* another *)
let c = "x"
`
	got := chunksFromSource(strings.NewReader(src))
	want := []string{`let a = add_error "A"`, `let b = add_error "B"`, `let c = "x"`}
	if !slices.Equal(got, want) {
		t.Errorf("chunksFromSource() = %q, want %q", got, want)
	}
}

func TestParseEntries(t *testing.T) {
	chunks := []string{
		`let message_deprecated = add_error "MESSAGE_DEPRECATED"`,
		`let auth_suffix = "_SUFFIX"`,
		`let joined = add_error $ message_deprecated ^ auth_suffix`,
		`let with_lit = add_error $ message_deprecated ^ "_LIT"`,
		`let spaced  =   add_error   "SPACED"`,
		`let unresolved = add_error $ missing ^ auth_suffix`,
		`let unresolved_lit = add_error $ missing ^ "_X"`,
		`let something_else = 42`,
	}
	entries, skipped := parseEntries(chunks)

	want := []ordEntry{
		{"message_deprecated", "MESSAGE_DEPRECATED"},
		{"joined", "MESSAGE_DEPRECATED_SUFFIX"},
		{"with_lit", "MESSAGE_DEPRECATED_LIT"},
		{"spaced", "SPACED"},
	}
	if !slices.Equal(entries, want) {
		t.Errorf("entries = %v, want %v", entries, want)
	}
	if len(skipped) != 3 {
		t.Errorf("skipped = %q, want the two unresolved concatenations and the non-error binding", skipped)
	}
}

func TestRender(t *testing.T) {
	src, divergent, err := render([]ordEntry{
		{"vm_toomany_vcpus", "VM_TOO_MANY_VCPUS"},
		{"handle_invalid", "HANDLE_INVALID"},
		{"sr_has_no_pbds", "SR_HAS_NO_PBDS"},
		{"sr_no_pbds", "SR_HAS_NO_PBDS"},
		{"pif_is_management_iface", "PIF_IS_MANAGEMENT_INTERFACE"},
	})
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by internal/cmd/generrors; DO NOT EDIT.

package xenapi

const (
	// The wire value is "VM_TOO_MANY_VCPUS".
	ErrVMToomanyVCPUs ErrorCode = "VM_TOO_MANY_VCPUS"
)

const (
	ErrHandleInvalid ErrorCode = "HANDLE_INVALID"
	ErrSRHasNoPBDs   ErrorCode = "SR_HAS_NO_PBDS"
)

const (
	// The wire value is "SR_HAS_NO_PBDS".
	ErrSRNoPBDs ErrorCode = "SR_HAS_NO_PBDS"
)

const (
	// The wire value is "PIF_IS_MANAGEMENT_INTERFACE".
	ErrPIFIsManagementIface ErrorCode = "PIF_IS_MANAGEMENT_INTERFACE"
)
`
	if string(src) != want {
		t.Errorf("render() =\n%s\nwant\n%s", src, want)
	}
	if divergent != 3 {
		t.Errorf("divergent = %d, want 3", divergent)
	}
}

func TestRenderRejectsNameCollision(t *testing.T) {
	_, _, err := render([]ordEntry{{"a_b", "A_B"}, {"a__b", "A__B"}})
	if err == nil {
		t.Fatal("render() succeeded although a_b and a__b map to the same Go name")
	}
}
