// compareReleases orders release names chronologically: code names in
// namedReleases order, then numbered releases by version, an unreleased
// "-next" after its base version.
func compareReleases(a, b string) int {
	ia := slices.IndexFunc(namedReleases, func(r struct{ code, product string }) bool { return r.code == a })
	ib := slices.IndexFunc(namedReleases, func(r struct{ code, product string }) bool { return r.code == b })
	switch {
	case ia >= 0 && ib >= 0:
		return cmp.Compare(ia, ib)
	case ia >= 0:
		return -1
	case ib >= 0:
		return 1
	}
	return slices.Compare(versionKey(a), versionKey(b))
}

func versionKey(release string) []int {
	base, next := strings.CutSuffix(release, "-next")
	var key []int
	for part := range strings.SplitSeq(base, ".") {
		n, _ := strconv.Atoi(part)
		key = append(key, n)
	}
	if next {
		key = append(key, 1)
	}
	return key
}

type lifecycleEntry struct {
	kind                            int // 0 method, 1 field, 2 class
	goName, wire                    string
	prototyped, deprecated, removed string
	reason                          string
}

// lifecycleStatus classifies l like lifecycleNotes: "removed",
// "deprecated", "experimental" or "".
func lifecycleStatus(l *xapiLifecycleInfo) (status string, e lifecycleEntry) {
	if l == nil {
		return "", e
	}
	for _, t := range l.Transitions {
		switch t.Transition {
		case "removed":
			e.removed, e.reason = t.Release, t.Description
		case "deprecated":
			e.deprecated = t.Release
			if e.removed == "" {
				e.reason = t.Description
			}
		case "prototyped":
			e.prototyped = t.Release
		}
	}
	e.reason = strings.TrimSpace(e.reason)
	switch {
	case e.removed != "":
		return "removed", e
	case e.deprecated != "":
		return "deprecated", e
	case e.prototyped != "" && l.State == "Prototyped_s":
		return "experimental", e
	}
	return "", e
}

// generateLifecycleDoc writes a Markdown table of every removed, deprecated
// and experimental class, field and message to path.
func (generator *apiGenerator) generateLifecycleDoc(path string) error {
	entries := map[string][]lifecycleEntry{}
	add := func(kind int, goName, wire string, l *xapiLifecycleInfo) {
		status, e := lifecycleStatus(l)
		if status != "" {
			e.kind, e.goName, e.wire = kind, goName, wire
			entries[status] = append(entries[status], e)
		}
	}
	for _, c := range generator.classes {
		class := exportedGoIdentifier(c.Name)
		add(2, class+"Class", c.Name, c.Lifecycle)
		for _, f := range c.Fields {
			add(1, class+"Record."+exportedGoIdentifier(f.Name), c.Name+"."+f.Name, f.Lifecycle)
		}
		for _, m := range c.Messages {
			add(0, class+"."+exportedGoIdentifier(m.Name), c.Name+"."+m.Name, m.Lifecycle)
		}
	}

	var b strings.Builder
	b.WriteString(`# API lifecycle

<!-- Code generated by internal/cmd/genapi; DO NOT EDIT. -->

Methods, fields and classes that XAPI removed, deprecated or only published as
prototyped (experimental), for the schema the bindings were generated from
(see ` + "`xenapi.SchemaXAPIRelease`" + `). Removed APIs are still generated and work
on hosts older than the release that removed them. Release code names are
mapped to products per the
[XAPI release list](https://xapi-project.github.io/xen-api/releases.html);
newer releases only have XAPI version numbers.
`)
	sections := []struct {
		status, title string
		columns       []string
		release       func(lifecycleEntry) string
		cells         func(lifecycleEntry) []string
	}{
		{"removed", "Removed", []string{"Go", "XenAPI", "Deprecated in", "Removed in", "Reason"},
			func(e lifecycleEntry) string { return e.removed },
			func(e lifecycleEntry) []string {
				return []string{release(e.deprecated), release(e.removed), cell(e.reason)}
			}},
		{"deprecated", "Deprecated", []string{"Go", "XenAPI", "Deprecated in", "Reason"},
			func(e lifecycleEntry) string { return e.deprecated },
			func(e lifecycleEntry) []string { return []string{release(e.deprecated), cell(e.reason)} }},
		{"experimental", "Experimental", []string{"Go", "XenAPI", "Prototyped in"},
			func(e lifecycleEntry) string { return e.prototyped },
			func(e lifecycleEntry) []string { return []string{release(e.prototyped)} }},
	}
	for _, s := range sections {
		list := entries[s.status]
		slices.SortFunc(list, func(a, b lifecycleEntry) int {
			return cmp.Or(-compareReleases(s.release(a), s.release(b)), cmp.Compare(a.kind, b.kind), strings.Compare(a.goName, b.goName))
		})
		fmt.Fprintf(&b, "\n## %s (%d)\n\nNewest first.\n\n| %s |\n|%s\n", s.title, len(list),
			strings.Join(s.columns, " | "), strings.Repeat(" --- |", len(s.columns)))
		for _, e := range list {
			row := append([]string{"`" + e.goName + "`", "`" + e.wire + "`"}, s.cells(e)...)
			fmt.Fprintf(&b, "| %s |\n", strings.Join(row, " | "))
		}
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func release(code string) string {
	if code == "" {
		return ""
	}
	for _, r := range namedReleases {
		if r.code == code {
			return fmt.Sprintf("`%s` (%s)", code, r.product)
		}
	}
	return "`" + code + "`"
}

func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
